#include <cstdint>
#include <cstring>
#include <limits>

extern "C" {
    #include "platform.h"
    #include "canard.h"
    #include "io/dronecan/dronecan.h"
    #include "io/dronecan/dronecan_gnss.h"
    #include "io/dronecan/dronecan_msg.h"

    static dronecanSubscriber_t subscription;
    static timeUs_t mockMicros;
    bool dronecanRegisterSubscriber(const dronecanSubscriber_t *subscriber)
    {
        subscription = *subscriber;
        return true;
    }
    timeUs_t micros(void)
    {
        return mockMicros;
    }
}

#include "gtest/gtest.h"

class DronecanGnssTest : public ::testing::Test {
protected:
    void SetUp() override
    {
        subscription = {};
        mockMicros = 1234;
        dronecanGnssInit();
        ASSERT_NE(nullptr, subscription.handler);
    }

    static void feed(float north = 12.5f, float east = -3.25f, float down = 1.5f,
        int64_t longitude = 3745678900LL, int64_t latitude = 5512345600LL,
        uint16_t length = 50, uint8_t status = 3)
    {
        uint8_t payload[50] = {};
        const int32_t altitude = 123450;
        const uint8_t satellites = 12;
        canardEncodeScalar(payload, 136, 37, &longitude);
        canardEncodeScalar(payload, 173, 37, &latitude);
        canardEncodeScalar(payload, 237, 27, &altitude);
        canardEncodeScalar(payload, 264, 32, &north);
        canardEncodeScalar(payload, 296, 32, &east);
        canardEncodeScalar(payload, 328, 32, &down);
        canardEncodeScalar(payload, 360, 6, &satellites);
        canardEncodeScalar(payload, 366, 2, &status);
        CanardRxTransfer transfer = {};
        transfer.payload_head = payload;
        transfer.payload_len = length;
        subscription.handler(nullptr, &transfer);
    }

    static bool accept(const CanardInstance *, uint64_t *signature, uint16_t id,
        CanardTransferType type, uint8_t)
    {
        if (id != subscription.dataTypeId || type != subscription.transferType) {
            return false;
        }
        *signature = subscription.signature;
        return true;
    }
    static void receive(CanardInstance *instance, CanardRxTransfer *transfer)
    {
        subscription.handler(instance, transfer);
    }
};

TEST_F(DronecanGnssTest, AcceptsReferenceFix2Transfer)
{
    // Generated by DroneCAN Python 1.0.27 from the standard Fix2 DSDL.
    const uint8_t data[][8] = {
        {0x67, 0x2f, 0, 0, 0, 0, 0, 0x87},
        {0, 0, 0, 0, 0, 0, 0, 0x27},
        {0, 0, 0, 0, 0, 0x34, 0x86, 0x07},
        {0x42, 0xdf, 0, 0x05, 0xc4, 0x7a, 0x40, 0x27},
        {0x40, 0, 0, 0x01, 0xd7, 0x10, 0x08, 0x07},
        {0, 0, 0x48, 0x41, 0, 0, 0x50, 0x27},
        {0xc0, 0, 0, 0xc0, 0x3f, 0x33, 0, 0x07},
        {0, 0, 0, 0x67},
    };
    uint8_t pool[1024] = {};
    CanardInstance instance;
    canardInit(&instance, pool, sizeof(pool), receive, accept, nullptr);
    canardSetLocalNodeID(&instance, 127);
    for (unsigned i = 0; i < 8; i++) {
        CanardCANFrame frame = {};
        frame.id = CANARD_CAN_FRAME_EFF | 0x1004272aU;
        frame.data_len = i == 7 ? 4 : 8;
        memcpy(frame.data, data[i], frame.data_len);
        ASSERT_GE(canardHandleRxFrame(&instance, &frame, mockMicros + i), 0);
    }
    gpsSolutionData_t solution;
    ASSERT_TRUE(dronecanGnssGetLatest(&solution));
    EXPECT_EQ(551234560, solution.llh.lat);
    EXPECT_EQ(374567890, solution.llh.lon);
    EXPECT_EQ(12345, solution.llh.altCm);
    EXPECT_EQ(12, solution.numSat);
    EXPECT_EQ(1250, solution.velned.velN);
    EXPECT_EQ(-325, solution.velned.velE);
    EXPECT_EQ(150, solution.velned.velD);
    EXPECT_EQ(1291, solution.groundSpeed);
    EXPECT_EQ(1300, solution.speed3d);
    EXPECT_EQ(3454, solution.groundCourse);
    EXPECT_EQ(mockMicros, dronecanGnssLastUpdateUs());
}

TEST_F(DronecanGnssTest, RejectsTruncatedPrefixWithoutPublication)
{
    gpsSolutionData_t solution;
    for (uint16_t length = 0; length < 46; length++) {
        feed(12.5f, -3.25f, 1.5f, 3745678900LL, 5512345600LL, length);
        EXPECT_FALSE(dronecanGnssGetLatest(&solution));
    }
    EXPECT_EQ(0U, dronecanGnssLastUpdateUs());
}

TEST_F(DronecanGnssTest, RejectsInvalidVelocityWithoutRefreshingLastSample)
{
    feed();
    gpsSolutionData_t before;
    ASSERT_TRUE(dronecanGnssGetLatest(&before));
    mockMicros++;
    for (const float value : {std::numeric_limits<float>::quiet_NaN(),
        std::numeric_limits<float>::infinity(), -std::numeric_limits<float>::infinity()}) {
        feed(value);
        feed(12.5f, value);
        feed(12.5f, -3.25f, value);
        gpsSolutionData_t after;
        ASSERT_TRUE(dronecanGnssGetLatest(&after));
        EXPECT_EQ(0, memcmp(&before, &after, sizeof(before)));
        EXPECT_EQ(1234U, dronecanGnssLastUpdateUs());
    }
}

TEST_F(DronecanGnssTest, RejectsInvalidCoordinates)
{
    gpsSolutionData_t solution;
    feed(0, 0, 0, 18000000001LL, 0);
    EXPECT_FALSE(dronecanGnssGetLatest(&solution));
    feed(0, 0, 0, -18000000001LL, 0);
    EXPECT_FALSE(dronecanGnssGetLatest(&solution));
    feed(0, 0, 0, 0, 9000000001LL);
    EXPECT_FALSE(dronecanGnssGetLatest(&solution));
    feed(0, 0, 0, 0, -9000000001LL);
    EXPECT_FALSE(dronecanGnssGetLatest(&solution));
    EXPECT_EQ(0U, dronecanGnssLastUpdateUs());
}

TEST_F(DronecanGnssTest, SaturatesFiniteVelocityAndPreservesNedSigns)
{
    feed(std::numeric_limits<float>::max(), -std::numeric_limits<float>::max(), 0);
    gpsSolutionData_t solution;
    ASSERT_TRUE(dronecanGnssGetLatest(&solution));
    EXPECT_EQ(INT16_MAX, solution.velned.velN);
    EXPECT_EQ(INT16_MIN, solution.velned.velE);
    EXPECT_EQ(0, solution.velned.velD);
    EXPECT_EQ(UINT16_MAX, solution.groundSpeed);
    EXPECT_EQ(UINT16_MAX, solution.speed3d);
    EXPECT_EQ(3150, solution.groundCourse);
}

TEST_F(DronecanGnssTest, ReportsLossOfFix)
{
    feed(0, 0, 0, 0, 0, 50, 0);
    gpsSolutionData_t solution;
    ASSERT_TRUE(dronecanGnssGetLatest(&solution));
    EXPECT_EQ(0, solution.numSat);
}
